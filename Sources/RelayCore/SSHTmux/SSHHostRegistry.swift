import Foundation

/// Relay's host list, rendered for the system OpenSSH client.
///
/// Every ssh/scp Relay runs gets `-F <configFile>`: a generated config with
/// one block per Relay host, followed by the user's own `~/.ssh/config`
/// and the system config — the same precedence OpenSSH applies normally,
/// with Relay's entry first. So a Relay host's hostname/user/port/key are
/// Relay's, while everything Relay doesn't model (agent settings,
/// `UseKeychain`, ProxyJump on an imported host, `SendEnv` from the system
/// config) keeps working exactly as before.
public final class SSHHostRegistry: @unchecked Sendable {
    public let configFile: URL
    private let userConfigPath: String
    private let systemConfigPath: String
    private let lock = NSLock()
    private var _hosts: [SSHHost] = []

    public init(
        configFile: URL,
        userConfigPath: String = SSHConfigDiscovery.defaultConfigPath,
        systemConfigPath: String = "/etc/ssh/ssh_config"
    ) {
        self.configFile = configFile
        self.userConfigPath = userConfigPath
        self.systemConfigPath = systemConfigPath
        // Written right away so ssh never sees a missing -F file (before
        // the host list loads it's just the includes: plain ssh behavior).
        writeConfig(hosts: [])
    }

    public var hosts: [SSHHost] {
        lock.withLock { _hosts }
    }

    public func host(alias: String) -> SSHHost? {
        lock.withLock { _hosts.first { $0.alias == alias } }
    }

    /// Called after every `setHosts` (e.g. to drop connection state tied
    /// to old settings).
    public var onHostsChanged: (@Sendable () -> Void)? {
        get { lock.withLock { _onHostsChanged } }
        set { lock.withLock { _onHostsChanged = newValue } }
    }
    private var _onHostsChanged: (@Sendable () -> Void)?

    public func setHosts(_ hosts: [SSHHost]) {
        lock.withLock { _hosts = hosts }
        writeConfig(hosts: hosts)
        onHostsChanged?()
    }

    private func writeConfig(hosts: [SSHHost]) {
        let text = Self.render(hosts: hosts, userConfigPath: userConfigPath, systemConfigPath: systemConfigPath)
        Self.writePrivately(text, to: configFile)
    }

    /// Writes `text` readable by the user only (hostnames, users and key
    /// paths aren't secrets, but they're nobody else's business).
    public static func writePrivately(_ text: String, to url: URL) {
        let fm = FileManager.default
        try? fm.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        do {
            try Data(text.utf8).write(to: url, options: .atomic)
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
        } catch {
            // ssh reports the unreadable config on its next run; nothing
            // useful to do here.
        }
    }

    /// The generated config. Pure; unit-tested.
    public static func render(hosts: [SSHHost], userConfigPath: String, systemConfigPath: String) -> String {
        var lines = [
            "# Generated by Relay from its host list — changes here are overwritten.",
            "# Relay's hosts come first; your own ssh config still applies for",
            "# anything they don't set.",
            "",
        ]
        for host in hosts {
            guard (try? host.validate()) != nil else {
                lines.append("# Skipped \(host.alias.filter { $0.isASCII && !$0.isNewline }): invalid settings")
                lines.append("")
                continue
            }
            lines.append(contentsOf: block(for: host))
            lines.append("")
        }
        // `Match all` closes the last Host block, so the includes apply to
        // every host instead of only the last one listed.
        lines.append("Match all")
        lines.append("Include \(quoted(userConfigPath))")
        lines.append("Include \(quoted(systemConfigPath))")
        lines.append("")
        return lines.joined(separator: "\n")
    }

    static func block(for host: SSHHost) -> [String] {
        var lines = ["Host \(host.alias)", "  HostName \(host.hostname)"]
        if let user = host.user, !user.isEmpty { lines.append("  User \(user)") }
        if let port = host.port { lines.append("  Port \(port)") }
        switch host.auth {
        case .automatic:
            break
        case .keyFile(let path, let certificate):
            lines.append("  IdentityFile \(quoted(tokenEscaped(path)))")
            if let certificate, !certificate.isEmpty {
                lines.append("  CertificateFile \(quoted(tokenEscaped(certificate)))")
            }
            // Passphrase-protected keys unlock from the login keychain
            // (and stay in the agent), as the user's own config usually
            // arranges.
            lines.append("  AddKeysToAgent yes")
            lines.append("  UseKeychain yes")
        case .password:
            lines.append("  PreferredAuthentications keyboard-interactive,password")
            lines.append("  PubkeyAuthentication no")
        case .storedKey:
            // Signs in with a key only Relay's built-in client holds; the
            // system ssh never connects to this host.
            lines.append("  # Relay key: built-in SSH client only")
        }
        return lines
    }

    private static func quoted(_ value: String) -> String {
        "\"\(value)\""
    }

    /// IdentityFile/CertificateFile expand `%` tokens.
    private static func tokenEscaped(_ path: String) -> String {
        path.replacingOccurrences(of: "%", with: "%%")
    }
}
